#!/usr/bin/env node
// scripts/gen-demo-flag-map.js
'use strict';

/**
 * Generates docs/demo-flag-map.md — which feature flags each 15-min security
 * demo step depends on, in beat order, so a presenter can eyeball readiness.
 *
 * GENERATED, not hand-written, and gated by --check in hygiene:check. A
 * hand-maintained map of this would drift the moment a flag or a beat changed,
 * and a demo map that lies is worse than none — the same failure mode as the
 * requiredDemoFlags mirror (PR #886) and the 202 all-green ledger rows.
 *
 *   node scripts/gen-demo-flag-map.js            write docs/demo-flag-map.md
 *   node scripts/gen-demo-flag-map.js --check    fail if the file is stale
 *   node scripts/gen-demo-flag-map.js --stdout   print, write nothing
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'demo-flag-map.md');

const { resolveUseCase, USE_CASES } = require(path.join(ROOT, 'demo_api_server/config/useCases.js'));
const {
  requiredFlagsForUseCase,
  MCP_GATEWAY_RUNTIME_FLAGS,
} = require(path.join(ROOT, 'demo_api_server/services/demoStepPrerequisites.js'));

/** Beat order + ucId + one-line action, parsed from the teleprompter script. */
function readBeats() {
  const src = fs.readFileSync(
    path.join(ROOT, 'demo_api_ui/src/components/demoScript.js'), 'utf8');
  const beats = [];
  // Backreference the opening quote: these strings contain apostrophes
  // ("the user's balance"), and a naive ["'] class truncates mid-word.
  const re = /ucId:\s*(["'])(.*?)\1[\s\S]{0,200}?action:\s*\n?\s*(["'])((?:\\.|(?!\3)[\s\S])*)\3[\s\S]{0,400}?what:\s*\n?\s*(["'])((?:\\.|(?!\5)[\s\S])*)\5/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    beats.push({ ucId: m[2], action: m[4], what: m[6] });
  }
  return beats;
}

/** SECURITY_DEMO_USE_CASE_IDS — the workbench group, 1:1 with the beats. */
function readStepIds() {
  const src = fs.readFileSync(
    path.join(ROOT, 'demo_api_ui/src/config/demoUseCaseSteps.js'), 'utf8');
  const m = src.match(/SECURITY_DEMO_USE_CASE_IDS\s*=\s*\[([\s\S]*?)\];/);
  if (!m) throw new Error('SECURITY_DEMO_USE_CASE_IDS not found');
  return [...m[1].matchAll(/["']([^"']+)["']/g)].map((x) => x[1]);
}

const esc = (s) => String(s || '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function build() {
  const beats = readBeats();
  const stepIds = readStepIds();

  const rows = beats.map((b, i) => {
    const uc = resolveUseCase(b.ucId, 'banking') || USE_CASES.find((u) => u.id === b.ucId) || {};
    const flags = requiredFlagsForUseCase(uc);
    // Everything requiredFlagsForUseCase returns is armed automatically when the
    // step runs — the workbench POSTs /api/use-cases/demo/run, which arms the
    // full set (routes/useCases.js). Split anyway so the gateway floor, which
    // every tool-dispatching step shares, is visible rather than repeated noise.
    const gateway = flags.filter((f) => MCP_GATEWAY_RUNTIME_FLAGS.includes(f));
    const specific = flags.filter((f) => !MCP_GATEWAY_RUNTIME_FLAGS.includes(f));
    return { n: i + 1, ...b, uc, flags, gateway, specific };
  });

  const allSpecific = [...new Set(rows.flatMap((r) => r.specific))].sort();
  const mismatch = stepIds.join(',') !== beats.map((b) => b.ucId).join(',');

  const L = [];
  L.push('# Demo flag map — 15-minute security-leader demo');
  L.push('');
  L.push('<!-- GENERATED by scripts/gen-demo-flag-map.js — do not edit by hand.');
  L.push('     Regenerate: npm run demo:flag-map     Verify: npm run demo:flag-map:check -->');
  L.push('');
  L.push('Which feature flags each demo step depends on, in the order you present them.');
  L.push('Use it to eyeball readiness before a demo.');
  L.push('');
  L.push('**The short version: you do not need to pre-arm the per-step flags.** Running a');
  L.push('step POSTs `/api/use-cases/demo/run`, which arms every flag that step declares');
  L.push('(`routes/useCases.js`). A flag reading `off` beforehand is normal. What matters');
  L.push('is the ambient list further down — those are *not* armed for you.');
  L.push('');
  if (mismatch) {
    L.push('> **WARNING — the teleprompter beats and the workbench group disagree.**');
    L.push('> `demoScript.js` beat order: `' + beats.map((b) => b.ucId).join(', ') + '`');
    L.push('> `SECURITY_DEMO_USE_CASE_IDS`: `' + stepIds.join(', ') + '`');
    L.push('> They are meant to be 1:1. Fix one of them before presenting.');
    L.push('');
  } else {
    L.push('Beat order and `SECURITY_DEMO_USE_CASE_IDS` agree (' + stepIds.length + ' steps).');
    L.push('');
  }

  L.push('## Steps');
  L.push('');
  L.push('| # | Use case | What it shows | Step-specific flag | Gateway floor |');
  L.push('|---|---|---|---|---|');
  for (const r of rows) {
    L.push('| ' + r.n
      + ' | `' + r.ucId + '` — ' + esc(r.uc.title || '')
      + ' | ' + esc(r.what).slice(0, 88)
      + ' | ' + (r.specific.length ? r.specific.map((f) => '`' + f + '`').join('<br>') : '—')
      + ' | ' + (r.gateway.length ? 'yes' : '—')
      + ' |');
  }
  L.push('');
  L.push('**Gateway floor** = `' + MCP_GATEWAY_RUNTIME_FLAGS.map((f) => '`' + f + '`').join(', ').replace(/`/g, '') + '`.');
  L.push('Every step that dispatches an MCP tool needs it. Armed on run like the rest —');
  L.push('but it is the one that took 22 use cases down when the UI mirror stopped');
  L.push('arming it (PR #886), so it is called out separately rather than repeated.');
  L.push('');
  L.push('Step-specific flags across the whole demo: '
    + (allSpecific.length ? allSpecific.map((f) => '`' + f + '`').join(', ') : 'none') + '.');
  L.push('');

  L.push('## Ambient — must be true BEFORE you start');
  L.push('');
  L.push('None of these are armed by running a step.');
  L.push('');
  L.push('| Setting | Wanted | Why |');
  L.push('|---|---|---|');
  L.push('| `ff_use_cases_launcher` | ON | Gates the `/use-cases` surface the demo runs from. |');
  L.push('| `ff_heuristic_enabled` | ON | The routing floor. Off, chips go to the LLM and answer non-deterministically. |');
  L.push('| `NODE_ENV` | not `production` | Attack sims return 403 `not_available_in_production` — that is Act 3. |');
  L.push('| Sign-in host | `local.ping-devops.com:4000` | Passkey rp.id. On `api.ping.demo` the session cookie lands elsewhere and every call 401s. |');
  L.push('| `MCP_MTLS_ENABLED` | `true` (default) | Gateway→MCP mTLS. Needs `certs/gw-mtls/` present — `run-docker.sh` generates it. |');
  L.push('| `BANKING_API_RESOURCE_URI` | `enduser.ping.demo` to show Step 9 | The MCP-spec hop. Set in `demo_mcp_server/.env`; empty disables it silently. |');
  L.push('');
  L.push('> **Rebuild `mcp-server` after pulling.** The mTLS-aware healthcheck lives in');
  L.push('> the image. With mTLS on and a stale image the container is permanently');
  L.push('> unhealthy while serving fine: `docker compose build mcp-server && docker compose up -d --force-recreate mcp-server`.');
  L.push('');

  L.push('## Checking live state');
  L.push('');
  L.push('```bash');
  L.push('npm run sweep:use-cases     # every use case x vertical, blocked rows clustered by cause');
  L.push('bash scripts/preflight-demo.sh   # ~10 min before showtime');
  L.push('```');
  L.push('');
  L.push('The sweep reads flags as a cold start would resolve them. It does **not** see');
  L.push('another process\'s unpersisted in-memory overrides — for the running stack, read');
  L.push('`GET /api/admin/feature-flags`.');
  L.push('');
  return L.join('\n') + '\n';
}

function main() {
  const out = build();
  if (process.argv.includes('--stdout')) { process.stdout.write(out); return; }
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) {
      console.error('✗ docs/demo-flag-map.md is stale — regenerate with: npm run demo:flag-map');
      process.exit(1);
    }
    console.log('[OK] docs/demo-flag-map.md is up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out, 'utf8');
  console.log('Wrote docs/demo-flag-map.md');
}

try { main(); } catch (err) {
  console.error('gen-demo-flag-map failed:', err && err.stack ? err.stack : err);
  process.exit(2);
}
