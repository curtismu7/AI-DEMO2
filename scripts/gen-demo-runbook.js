#!/usr/bin/env node
'use strict';
/**
 * gen-demo-runbook.js generate|check — the presenter's live-rescue page.
 *
 * One table per vertical, generated from useCases.js (the same SoT as the docs,
 * so it cannot drift — `check` fails pre-push when stale, exactly like
 * use-cases:docs:check). For each chip: what to type, what must happen, what to
 * say, and the fallback ladder when it fails live:
 *
 *   Layer 1  switch Agent mode to Heuristics (deterministic routing, real tools)
 *   Layer 2  PATCH /api/admin/feature-flags {"updates":{"ff_authorize_real":false}}
 *            (+ authz-server up) — real chips, simulated policy backend
 *   Layer 3  click "Show the expected result (REPLAY)" on the failure message —
 *            captured known-good run, always labeled, never impersonates live proof
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'use-cases', 'demo-runbook.md');
const A2A_UNROUTABLE = /specialist/i;

function generateContent() {
  const { USE_CASES, VERTICALS, resolveUseCase } = require(path.join(ROOT, 'demo_api_server', 'config', 'useCases.js'));
  const lines = [
    '<!-- AUTO-GENERATED by scripts/gen-demo-runbook.js — do not hand-edit -->',
    '',
    '# Live Demo Runbook — chips, expectations, and the fallback ladder',
    '',
    '> Regenerate: `npm run use-cases:gen` (from `demo_api_server/`).',
    '> Preflight ~10 min before showtime: `bash scripts/preflight-demo.sh`.',
    '',
    '## The fallback ladder (in order — each step is visibly labeled, never silent)',
    '',
    '1. **Real LLM run** — the default. If it fails:',
    '2. **Heuristics mode** — switch Agent mode to Heuristics (one click; deterministic routing, same real tools/gateway/policy).',
    '3. **Mock Authorize** — `PATCH /api/admin/feature-flags {"updates":{"ff_authorize_real":false}}` with authz-server up (real chips + tools, mock policy backend). Outage fallback only; last resort before replay.',
    '4. **REPLAY** — click "Show the expected result (REPLAY)" on the failure message: a captured known-good run, labeled with its capture date. Token chain / activity panels stay empty — live proof only.',
    '',
  ];
  for (const vertical of VERTICALS) {
    const seen = new Set();
    const rows = [];
    for (const u of USE_CASES) {
      const uc = resolveUseCase(u.id, vertical) || u;
      const t = uc.trigger || {};
      if (t.type !== 'chip' || !t.text || A2A_UNROUTABLE.test(t.text) || seen.has(t.text)) continue;
      seen.add(t.text);
      rows.push(`| ${u.id} | \`${t.text}\` | \`${uc.expectedOutcome || 'n/a'}\` | ${uc.whatToSay ? uc.whatToSay.replace(/\|/g, '\\|') : ''} |`);
    }
    if (!rows.length) continue;
    lines.push(`## ${vertical}`, '', '| UC | Type this | Must happen | What to say |', '|---|---|---|---|', ...rows, '');
  }
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  const mode = process.argv[2] || 'generate';
  const content = generateContent();
  if (mode === 'check') {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== content) {
      console.error('[gen-demo-runbook] DRIFT DETECTED in demo-runbook.md');
      console.error('Run: npm run use-cases:gen (from demo_api_server/)');
      process.exit(1);
    }
    console.log('[gen-demo-runbook] OK — runbook is current.');
  } else {
    fs.writeFileSync(OUT, content);
    console.log('[gen-demo-runbook] wrote ' + path.relative(ROOT, OUT));
  }
}

module.exports = { generateContent, OUT };
