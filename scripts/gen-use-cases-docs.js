#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'docs/use-cases');
const { USE_CASES } = require(path.join(ROOT, 'demo_api_server/config/useCases'));

const MATURITY_GLYPH = { works: '✅', 'needs-console-import': '📥', 'needs-build': '🏗️' };
function maturityGlyph(m) { return m.startsWith('flag:') ? '🚩' : (MATURITY_GLYPH[m] || m); }

const TRACK_ORDER = ['foundations', 'demo', 'controls', 'attacks', 'hitl', 'tools', 'learn'];

function ucDoc(uc) {
  const owasp = uc.owasp && uc.owasp.threats && uc.owasp.threats.length
    ? `🛡️ **OWASP ASI** — Threats: ${uc.owasp.threats.join(', ')} · Sections: ${uc.owasp.sections.join(', ')}`
    : '';

  let triggerDesc;
  if (uc.trigger.type === 'chip') {
    triggerDesc = `Chip message: \`${uc.trigger.text}\``;
  } else if (uc.trigger.type === 'attack') {
    triggerDesc = `Attack simulation: \`${uc.trigger.sim}\``;
  } else {
    triggerDesc = `Trigger (${uc.trigger.type}): \`${JSON.stringify(uc.trigger)}\``;
  }

  const codeRefs = uc.codeRefs.map((r) => `- \`${r}\``).join('\n');

  const maturityNote = uc.whatToEnable
    ? `\n\n> **To enable:** ${uc.whatToEnable}`
    : '';

  return [
    `<!-- AUTO-GENERATED by scripts/gen-use-cases-docs.js — do not hand-edit -->`,
    ``,
    `# ${uc.id} — ${uc.title}`,
    ``,
    `**Track:** ${uc.track}  `,
    `**Maturity:** ${maturityGlyph(uc.maturity)} \`${uc.maturity}\`${maturityNote}  `,
    owasp ? `**OWASP:** ${owasp}` : '',
    ``,
    `## Buyer Story`,
    ``,
    uc.buyerStory,
    ``,
    `## PingOne Solution`,
    ``,
    uc.pingOneSolution,
    ``,
    `## How to Run`,
    ``,
    `**Trigger:** ${triggerDesc}  `,
    `**Expected outcome:** \`${uc.expectedOutcome}\``,
    ``,
    `## What to Say`,
    ``,
    `> ${uc.whatToSay}`,
    ``,
    `## Evidence`,
    ``,
    `**Token chain steps:** ${uc.evidence.tokenChain.join(' → ')}  `,
    `**Activity categories:** ${uc.evidence.activity.join(', ')}`,
    ``,
    `## Code References`,
    ``,
    codeRefs,
    ``,
    uc.advanced ? `> **Advanced:** This is an appendix use case (observation-only / flag-gated today).` : '',
    ``,
    `---`,
    ``,
    `_[Back to index](./README.md) · [Audit table](./audit-table.md)_`,
    ``,
  ].filter((l) => l !== undefined && l !== null).join('\n');
}

function indexDoc() {
  const lines = [
    `<!-- AUTO-GENERATED by scripts/gen-use-cases-docs.js — do not hand-edit -->`,
    ``,
    `# AI-Agent Security Use Cases`,
    ``,
    `> Generated from \`demo_api_server/config/useCases.js\`.`,
    `> Regenerate: \`npm run use-cases:docs:gen\` (from \`demo_api_server/\`).`,
    ``,
    `See also: [Audit Table](./audit-table.md), [Step Verification Report](./step-verification-report.md)`,
    ``,
  ];

  const byTrack = {};
  for (const uc of USE_CASES) {
    (byTrack[uc.track] = byTrack[uc.track] || []).push(uc);
  }

  const tracks = TRACK_ORDER.filter((t) => byTrack[t]);
  for (const track of tracks) {
    const ucList = byTrack[track];
    lines.push(`## ${track.charAt(0).toUpperCase() + track.slice(1)}`, '');
    for (const uc of ucList) {
      const owasp = uc.owasp && uc.owasp.threats && uc.owasp.threats.length ? ' 🛡️' : '';
      lines.push(`- [**${uc.id}** — ${uc.title}](./${uc.useCaseId}.md) ${maturityGlyph(uc.maturity)}${owasp}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

function generateAll() {
  // Returns map of relativePath → content
  const files = {};
  for (const uc of USE_CASES) {
    files[`${uc.useCaseId}.md`] = ucDoc(uc);
  }
  files['README.md'] = indexDoc();
  return files;
}

const [, , mode] = process.argv;

if (mode === 'generate') {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const files = generateAll();
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(OUT_DIR, name), content, 'utf8');
  }
  console.log(`[gen-use-cases-docs] written: ${Object.keys(files).length} files to ${OUT_DIR}`);
} else if (mode === 'check') {
  const files = generateAll();
  const drifted = [];
  for (const [name, content] of Object.entries(files)) {
    const filePath = path.join(OUT_DIR, name);
    let existing = '';
    try { existing = fs.readFileSync(filePath, 'utf8'); } catch (_) { /* absent */ }
    if (existing !== content) drifted.push(name);
  }
  if (drifted.length > 0) {
    console.error(`[gen-use-cases-docs] DRIFT DETECTED in: ${drifted.join(', ')}`);
    console.error('Run: npm run use-cases:docs:gen (from demo_api_server/)');
    process.exit(1);
  }
  console.log(`[gen-use-cases-docs] OK — all ${Object.keys(files).length} docs are current.`);
} else {
  console.error('Usage: gen-use-cases-docs.js generate|check');
  process.exit(1);
}
