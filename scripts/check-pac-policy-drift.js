#!/usr/bin/env node
/**
 * check-pac-policy-drift.js — no-drift gate for the hand-authored PaC policy.
 *
 * Regression (#1279): the airlines vertical added `sensitive_passenger_record`
 * with `a2aDelegated: true` in scope-topology.json, but nobody added it to the
 * `DenyA2aDelegationRequired` rule in pac/policies/mcp-delegation.yaml. The tool
 * required A2A delegation in code while the deployed policy did not know it
 * existed, so the rule could never fire against it.
 *
 * Every other link in that chain is generated or gated — scope-topology.json has
 * topology:verify, the P1AZ snapshot is generated by snapshots/gen-authorize-
 * snapshot.js and checked by snapshot:check, the MCP tool catalogs are generated
 * into both trees and compared. pac/policies/*.yaml is the one hand-maintained
 * link and it silently fell behind.
 *
 * This check closes that gap: every rule listed in BINDINGS has its tool list
 * DERIVED from scope-topology.json and compared both ways. No tool name is
 * hand-typed here, so a new vertical cannot reintroduce the bug.
 *
 *   node scripts/check-pac-policy-drift.js
 *   npm run topology:verify        (step 8/8)
 *
 * NOTE — two further drifts are known and deliberately NOT gated here yet,
 * because closing them changes runtime demo behaviour (new HITL / step-up
 * prompts) and that needs its own reviewed change, not a silent rider on a
 * guard. Both are mechanically derivable and each is a one-entry addition to
 * BINDINGS once the behaviour change is approved:
 *   - RequireHitlConsent  is missing sensitive_airline_bookings and
 *     sensitive_passenger_record  (challengeType == 'consent' && surface == 'gateway')
 *   - RequireMcpStepUp    is missing cancel_airline_reservation and
 *     create_wire_transfer         (challengeType == 'step_up' && surface == 'gateway')
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

// PAC_DRIFT_ROOT lets the negative tests point at a fixture tree; default is the
// repo root next to this script (so `node scripts/...` works from anywhere).
const ROOT = process.env.PAC_DRIFT_ROOT
  ? path.resolve(process.env.PAC_DRIFT_ROOT)
  : path.join(__dirname, '..');

const SOT_REL = 'scope-topology.json';
const POLICY_REL = path.join('pac', 'policies', 'mcp-delegation.yaml');

/**
 * Rule <-> source-of-truth bindings.
 *
 * `derive` receives scope-topology.json's `tools` map and returns the tool names
 * the rule's `Request.ToolName in (...)` list must contain — exactly, no more
 * and no less. Deriving (rather than listing) is the whole point: adding a
 * vertical with a new delegated tool moves this expectation automatically.
 */
const BINDINGS = [
  {
    file: POLICY_REL,
    rule: 'DenyA2aDelegationRequired',
    source: "tools with a2aDelegated: true in scope-topology.json",
    fix: 'add the tool to the Request.ToolName list of rule DenyA2aDelegationRequired',
    derive: (tools) =>
      Object.keys(tools).filter((n) => tools[n] && tools[n].a2aDelegated === true),
  },
];

const fails = [];
const fail = (msg) => fails.push(msg);

function readOrDie(rel) {
  const abs = path.join(ROOT, rel);
  try {
    return fs.readFileSync(abs, 'utf8');
  } catch (err) {
    fail(`${rel}: cannot read (${err.code || err.message})`);
    return null;
  }
}

/**
 * Strip the trailing `tests:` block. Test fixtures name tools too, and matching
 * a ToolName there instead of in the rule would let a deleted rule pass.
 */
function policySection(text) {
  const parts = text.split(/^tests:/m);
  return parts[0];
}

/**
 * Extract the `Request.ToolName in ("a", "b", ...)` list from one named rule.
 * Returns an array of names, or null when the rule (or its list) is absent —
 * both of which are failures, never a vacuous pass.
 */
function toolListForRule(policyText, ruleName) {
  const section = policySection(policyText);
  // `[ \t]*` not `\s*`: \s matches newlines, so `^\s*rule` would anchor on a
  // preceding blank line and swallow the declaration into the indent.
  const start = section.search(new RegExp(`^[ \\t]*rule[ \\t]+${ruleName}[ \\t]+(deny|permit)\\b`, 'm'));
  if (start === -1) return null;
  const rest = section.slice(start);
  // Body ends at the next `rule <Name>` declaration (or end of the policy).
  // Search AFTER this rule's own declaration line, or `^` would match it again.
  const eol = rest.indexOf('\n');
  const nextRule =
    eol === -1 ? -1 : rest.slice(eol + 1).search(/^[ \t]*rule[ \t]+\w+[ \t]+(deny|permit)\b/m);
  const body = nextRule === -1 ? rest : rest.slice(0, eol + 1 + nextRule);
  const list = body.match(/Request\.ToolName\s+in\s+\(([\s\S]*?)\)/);
  if (!list) return null;
  return [...list[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

const sotText = readOrDie(SOT_REL);
let tools = null;
if (sotText) {
  try {
    tools = JSON.parse(sotText).tools || {};
  } catch (err) {
    fail(`${SOT_REL}: invalid JSON (${err.message})`);
  }
}

const policyCache = new Map();
function policyFor(rel) {
  if (!policyCache.has(rel)) policyCache.set(rel, readOrDie(rel));
  return policyCache.get(rel);
}

if (tools) {
  for (const b of BINDINGS) {
    const policyText = policyFor(b.file);
    if (!policyText) continue;

    const expected = b.derive(tools).slice().sort();
    if (expected.length === 0) {
      fail(
        `${SOT_REL}: derived an EMPTY tool set for ${b.rule} (${b.source}). ` +
          'Refusing to pass — an empty expectation would make this gate inert.',
      );
      continue;
    }

    const actual = toolListForRule(policyText, b.rule);
    if (actual === null) {
      fail(
        `${b.file}: rule ${b.rule} is missing, renamed, or has no ` +
          '`Request.ToolName in (...)` list. This gate cannot verify it.',
      );
      continue;
    }

    const missing = expected.filter((n) => !actual.includes(n));
    const extra = actual.filter((n) => !expected.includes(n));

    for (const n of missing) {
      fail(
        `${b.file}: rule ${b.rule} does NOT list "${n}", but ${b.source}. ` +
          `The deployed policy cannot enforce the rule against it. Fix: ${b.fix}.`,
      );
    }
    for (const n of extra) {
      const why = Object.prototype.hasOwnProperty.call(tools, n)
        ? `it is not among ${b.source}`
        : `no such tool exists in ${SOT_REL}`;
      fail(
        `${b.file}: rule ${b.rule} lists "${n}" but ${why}. ` +
          'Stale entry — remove it, or restore the tool in scope-topology.json.',
      );
    }
  }
}

if (fails.length) {
  console.error('❌ PaC policy drift FAILED:\n');
  for (const f of fails) console.error('  ' + f);
  console.error(
    '\npac/policies/*.yaml is hand-authored and has no generator. A fix in git is\n' +
      'NOT enforced until a human runs ./scripts/pac-deploy.sh (see pac/README.md).\n',
  );
  process.exit(1);
}

const summary = BINDINGS.map((b) => `${b.rule}=${b.derive(tools).length}`).join(' ');
console.log(`✅ PaC policy in sync with scope-topology.json (${summary})`);
