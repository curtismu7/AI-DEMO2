#!/usr/bin/env node
/*
 * gen-feature-data.js — collect each vertical's feature-page record from its own
 * directory and emit the backend data file the demo data service serves, so a
 * new vertical's feature-page data lives WITH the vertical (config/verticals/<id>/
 * feature-data.json) instead of being hand-added to demo_api_resource_server.
 *
 * For every vertical whose manifest declares a `featurePage` AND ships a
 * feature-data.json, this writes an entry keyed by the backend route segment
 * (== manifest.featurePage.dataKey, which is what the gateway's
 * APIKEY_BACKEND_ROUTES sends) into:
 *   demo_api_resource_server/feature-records.generated.json
 * which server.js merges over its inline VERTICALS map (inline = legacy verticals
 * not yet migrated; generated wins). Additive + backward-compatible.
 *
 * Usage:
 *   node scripts/gen-feature-data.js generate   # (re)write the generated file
 *   node scripts/gen-feature-data.js check      # exit 1 if it is stale vs the per-vertical sources
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const VERTICALS_DIR = path.join(ROOT, 'demo_api_server', 'config', 'verticals');
const OUT_PATH = path.join(ROOT, 'demo_api_resource_server', 'feature-records.generated.json');

function collect() {
  // eslint-disable-next-line global-require
  const { verticalManifest } = require('../demo_api_server/services/verticalManifest');
  verticalManifest.init();
  const records = {};
  for (const summary of verticalManifest.list()) {
    let m;
    try { m = verticalManifest.resolver.resolve(summary.id); } catch (_e) { continue; }
    const fp = m && m.featurePage;
    if (!fp || !fp.dataKey) continue;
    const dataFile = path.join(VERTICALS_DIR, summary.id, 'feature-data.json');
    if (!fs.existsSync(dataFile)) continue; // not migrated → still served from server.js inline map
    const data = JSON.parse(fs.readFileSync(dataFile, 'utf8'));
    records[fp.dataKey] = { noun: data.noun || `${summary.id} record`, record: data.record };
  }
  return records;
}

function render(records) {
  const ordered = {};
  ordered._generated = 'Generated by scripts/gen-feature-data.js from config/verticals/<id>/feature-data.json — do NOT hand-edit.';
  for (const k of Object.keys(records).sort()) ordered[k] = records[k];
  return `${JSON.stringify(ordered, null, 2)}\n`;
}

function main() {
  const mode = process.argv[2] || 'generate';
  const next = render(collect());

  if (mode === 'check') {
    const current = fs.existsSync(OUT_PATH) ? fs.readFileSync(OUT_PATH, 'utf8') : '';
    if (current === next) {
      console.log('[OK] feature-records.generated.json is up to date.');
      return;
    }
    console.error('[FAIL] feature-records.generated.json is stale. Run: node scripts/gen-feature-data.js generate');
    process.exit(1);
  }

  if (mode === 'generate') {
    fs.writeFileSync(OUT_PATH, next);
    const count = Object.keys(JSON.parse(next)).filter((k) => k !== '_generated').length;
    console.log(`[OK] Wrote ${path.relative(ROOT, OUT_PATH)} with ${count} migrated feature record(s).`);
    return;
  }

  console.error(`Unknown mode "${mode}". Use "generate" or "check".`);
  process.exit(2);
}

main();
