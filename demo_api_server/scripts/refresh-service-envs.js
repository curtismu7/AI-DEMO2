#!/usr/bin/env node
/**
 * refresh-service-envs.js
 *
 * Queries PingOne Management API using worker credentials from demo_api_server/.env,
 * then writes a correct .env for every dependent service.  Called from run.sh before
 * any service starts, replacing the brittle ensure_service_env / patch_* bash chain.
 *
 * If the api_server .env is missing, bootstrap hasn't run yet — exit 0 (silent no-op).
 * If PingOne is unreachable, print a warning and exit 0 — services start with whatever
 * .env is already on disk (same behaviour as before this script existed).
 */

'use strict';

const fs   = require('fs');
const path = require('path');
const https = require('https');
const http  = require('http');

const ROOT = path.resolve(__dirname, '..', '..');
const API_ENV = path.join(ROOT, 'demo_api_server', '.env');

// ── Helpers ────────────────────────────────────────────────────────────────

function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const raw of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    const key = line.slice(0, eq).trim();
    let val = line.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

function writeEnvFile(filePath, vars) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) return; // service not installed — skip
  const lines = [
    '# Auto-generated by demo_api_server/scripts/refresh-service-envs.js',
    '# Do not edit by hand — changes will be overwritten on next ./run.sh',
    '',
    ...Object.entries(vars).map(([k, v]) => {
      // Quote values containing spaces or special chars
      const needsQuote = /[\s$`"'\\;&|<>]/.test(v);
      return `${k}=${needsQuote ? `"${v.replace(/"/g, '\\"')}"` : v}`;
    }),
  ];
  fs.writeFileSync(filePath, lines.join('\n') + '\n', 'utf8');
}

function httpRequest(opts, postData) {
  return new Promise((resolve, reject) => {
    const lib = opts.protocol === 'http:' ? http : https;
    const req = lib.request(opts, res => {
      let body = '';
      res.on('data', c => { body += c; });
      res.on('end', () => {
        try { resolve({ status: res.statusCode, data: JSON.parse(body) }); }
        catch (_) { resolve({ status: res.statusCode, data: body }); }
      });
    });
    req.on('error', reject);
    req.setTimeout(10000, () => { req.destroy(new Error('timeout')); });
    if (postData) req.write(postData);
    req.end();
  });
}

async function getWorkerToken(envId, clientId, clientSecret, region) {
  const auth = Buffer.from(`${clientId}:${clientSecret}`).toString('base64');
  const body = 'grant_type=client_credentials';
  const res = await httpRequest({
    protocol: 'https:',
    hostname: `auth.pingone.${region}`,
    path: `/${envId}/as/token`,
    method: 'POST',
    headers: {
      'Authorization': `Basic ${auth}`,
      'Content-Type': 'application/x-www-form-urlencoded',
      'Content-Length': Buffer.byteLength(body),
    },
  }, body);
  if (res.status !== 200 || !res.data.access_token) {
    throw new Error(`Worker token failed (${res.status}): ${JSON.stringify(res.data)}`);
  }
  return res.data.access_token;
}

async function pingoneGet(token, region, envId, path_) {
  const res = await httpRequest({
    protocol: 'https:',
    hostname: `api.pingone.${region}`,
    path: `/v1/environments/${envId}${path_}`,
    method: 'GET',
    headers: { 'Authorization': `Bearer ${token}` },
  });
  if (res.status !== 200) {
    throw new Error(`GET ${path_} failed (${res.status}): ${JSON.stringify(res.data)}`);
  }
  return res.data;
}

// ── Resolve apps and resources from PingOne ────────────────────────────────

async function resolveAppsByName(token, region, envId, targetNames) {
  // targetNames: { logicalKey: 'Exact PingOne App Name', ... }
  const data = await pingoneGet(token, region, envId, '/applications?limit=100');
  const apps = data._embedded?.applications || [];
  const result = {};
  for (const [key, name] of Object.entries(targetNames)) {
    const app = apps.find(a => a.name === name);
    if (app) result[key] = { id: app.id, clientId: app.clientId, name: app.name };
  }
  return result;
}

async function getAppSecret(token, region, envId, appId) {
  try {
    const data = await pingoneGet(token, region, envId, `/applications/${appId}/secret`);
    return data.secret || data.value || '';
  } catch (_) { return ''; }
}

async function resolveResourcesByAudience(token, region, envId, targetAudiences) {
  // targetAudiences: { logicalKey: 'audience.string', ... }
  const data = await pingoneGet(token, region, envId, '/resources?limit=100');
  const resources = data._embedded?.resources || [];
  const result = {};
  for (const [key, aud] of Object.entries(targetAudiences)) {
    const r = resources.find(res => (res.audience || []).includes(aud) ||
                                     res.audience === aud);
    if (r) result[key] = { id: r.id, audience: Array.isArray(r.audience) ? r.audience[0] : r.audience };
  }
  return result;
}

