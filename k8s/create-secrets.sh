#!/bin/bash
# k8s/create-secrets.sh — create K8s secrets from local files
# Run once before deploy.sh, or re-run to rotate.
#
# Mirrors docker-compose's per-service env_file model: each service that has its
# own .env in the repo gets its own K8s secret, so MCP / langchain / agents
# receive the same credentials they do under `docker compose`.
#
# Quote handling: we SOURCE each .env (shell strips quotes) and emit
# --from-literal pairs. We deliberately do NOT use --from-env-file, which keeps
# surrounding quotes literally and corrupts secrets containing ~ . - etc.
#
# Prerequisites:
#   - demo_api_server/.env must exist (generated by bootstrap)
#   - certs/api.ping.demo+2.pem and certs/api.ping.demo+2-key.pem must exist
#   - (optional) <HELIX_AGENT_ID>.json keyfile (e.g. LLM2.json) for HELIX_API_KEY,
#     unless HELIX_API_KEY is already set in demo_api_server/.env
#
# Worktree fallback: .env files and certs are gitignored machine-local assets,
# so they do NOT travel to linked git worktrees. When this script runs from a
# worktree that lacks them, we transparently source the assets from the primary
# checkout (resolved via `git rev-parse --git-common-dir`) instead of failing.

set -e

DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --check|--dry-run) DRY_RUN=1 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
NS="${K8S_NAMESPACE:-ai-demo}"

# Snapshot the caller's PUBLIC_APP_URL before any secret_from_envfile call can
# clobber it: secret_from_envfile does `set -o allexport; source $env_file`,
# which pollutes THIS script's own variable namespace with every key in each
# service .env — including PUBLIC_APP_URL from demo_api_server/.env (the
# local dev default). That silently overwrites a caller-supplied
# PUBLIC_APP_URL before override_redirect_uris_for_public_origin ever reads
# it, even when the caller exported it correctly. Broke live sign-in twice
# (2026-07-13) via the normal se-update-code.sh path, not just standalone runs.
CALLER_PUBLIC_APP_URL="${PUBLIC_APP_URL:-}"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'

info()    { echo -e "${GREEN}[INFO]${NC} $1"; }
warn()    { echo -e "${YELLOW}[WARN]${NC} $1"; }
die()     { echo -e "${RED}[ERROR]${NC} $1"; exit 1; }

# ── Resolve where the gitignored, machine-local assets actually live ─────────
# Prefer this checkout. If its .env is missing (typical when running from a git
# worktree, since gitignored files don't get checked out there), fall back to
# the primary checkout that owns the shared .git directory.
ASSET_ROOT="$REPO_ROOT"
if [ ! -f "$ASSET_ROOT/demo_api_server/.env" ]; then
  if git_common="$(git -C "$REPO_ROOT" rev-parse --git-common-dir 2>/dev/null)"; then
    case "$git_common" in
      /*) : ;;                                   # already absolute
      *)  git_common="$REPO_ROOT/$git_common" ;; # relativize to this checkout
    esac
    primary_root="$(cd "$(dirname "$git_common")" && pwd)"
    if [ "$primary_root" != "$REPO_ROOT" ] && [ -f "$primary_root/demo_api_server/.env" ]; then
      warn "demo_api_server/.env not found under $REPO_ROOT (likely a git worktree)."
      warn "Falling back to primary checkout for machine-local assets: $primary_root"
      ASSET_ROOT="$primary_root"
    fi
  fi
fi

# ── --check/--dry-run scope warning ───────────────────────────────────────────
# The flag only wraps secret_from_envfile()'s own value-resolution report (per
# the plan's Testing section — a vault-vs-.env SOURCE preview, not a whole-
# script dry-run). Every other mutation below (TLS-certs apply, service-API-key
# / internal-secret alignment, Helix/Google/Groq/Anthropic key mirroring,
# ping-mcpgw-secrets, ping-gateway-config, and the final rollout-restart loop)
# still runs for real. Say so loudly so nobody mistakes --check for a safe
# no-op against a live shared cluster.
if [ "$DRY_RUN" = "1" ]; then
  warn "--check/--dry-run only previews vault-vs-.env value SOURCE for secret_from_envfile() calls."
  warn "It is NOT a full dry-run — this run still performs every other kubectl mutation in this script"
  warn "(TLS-certs apply, key alignment/mirroring, ping-mcpgw-secrets, ping-gateway-config, and the"
  warn "final rollout-restart of every deployment in namespace $NS)."
fi

# ── Vault: preflight + cache the key list once, before ANY kubectl call, so a
# missing/wrong VAULT_PASSWORD aborts before this script touches the live
# cluster at all (a vault failure discovered only at the first
# secret_from_envfile() call would leave the tls-certs secret already applied
# — a partial write). Fail closed: no vault script, no VAULT_PASSWORD → abort,
# don't silently fall back to .env for what should be vault-only secrets.
VAULT_SCRIPT="$REPO_ROOT/demo_api_server/scripts/vault.js"
[ -f "$VAULT_SCRIPT" ] || die "vault script not found at $VAULT_SCRIPT"
# secrets.vault is gitignored, same worktree-fallback need as VAULT_PASSWORD
# below — default to ASSET_ROOT (main checkout when run from a worktree)
# rather than requiring every caller to export VAULT_PATH by hand.
export VAULT_PATH="${VAULT_PATH:-$ASSET_ROOT/secrets.vault}"
if [ -z "${VAULT_PASSWORD:-}" ] && [ -f "$ASSET_ROOT/demo_api_server/.env" ]; then
  VAULT_PASSWORD="$(grep -E '^VAULT_PASSWORD=.+' "$ASSET_ROOT/demo_api_server/.env" | head -1 | cut -d= -f2- | tr -d '"')"
fi
[ -n "${VAULT_PASSWORD:-}" ] || die "VAULT_PASSWORD is required (export it, or set it in demo_api_server/.env)"
info "Reading vault key list..."
VAULT_KEYS="$(VAULT_PASSWORD="$VAULT_PASSWORD" node "$VAULT_SCRIPT" list)" \
  || die "vault: failed to list keys — check VAULT_PASSWORD and secrets.vault"

vault_has_key() {
  # Exact-line match against the cached newline-separated key list.
  printf '%s\n' "$VAULT_KEYS" | grep -qxF -- "$1"
}

vault_get() {
  VAULT_PASSWORD="$VAULT_PASSWORD" node "$VAULT_SCRIPT" get "$1" \
    || die "vault: failed to read $1"
}

# ── Preflight ─────────────────────────────────────────────────────────────────
[ -f "$ASSET_ROOT/demo_api_server/.env" ] || die "demo_api_server/.env not found. Run bootstrap first."
[ -f "$ASSET_ROOT/certs/api.ping.demo+2.pem" ]     || die "certs/api.ping.demo+2.pem not found. Run bootstrap first."
[ -f "$ASSET_ROOT/certs/api.ping.demo+2-key.pem" ] || die "certs/api.ping.demo+2-key.pem not found. Run bootstrap first."
[ -f "$ASSET_ROOT/certs/rootCA.pem" ]              || die "certs/rootCA.pem not found. Run ./run.sh once to copy the mkcert root CA."
kubectl get ns "$NS" &>/dev/null || die "Namespace $NS not found. Apply 01-namespace.yaml first."

# ── TLS secret from mkcert certs ─────────────────────────────────────────────
info "Creating tls-certs secret..."
# ca-bundle-with-mkcert.pem (system roots + mkcert root CA) lets the Python
# agents verify the BFF's mkcert cert via SSL_CERT_FILE without breaking
# external HTTPS — same bundle docker-compose mounts. Ship it when present.
CA_BUNDLE_ARG=()
if [ -f "$ASSET_ROOT/certs/ca-bundle-with-mkcert.pem" ]; then
  CA_BUNDLE_ARG=(--from-file=ca-bundle-with-mkcert.pem="$ASSET_ROOT/certs/ca-bundle-with-mkcert.pem")
fi
# pg-server.p12: PingGateway's admin.json (HTTPS 3036 change, 2026-08-17) fatals
# at startup with "The file related to the keystore does not exist" without it.
# Generated locally by scripts/ensure-pinggateway-tls-cert.sh (gitignored).
PG_TLS_ARG=()
if [ -f "$ASSET_ROOT/certs/pg-tls/pg-server.p12" ]; then
  PG_TLS_ARG=(--from-file=pg-server.p12="$ASSET_ROOT/certs/pg-tls/pg-server.p12")
else
  warn "  certs/pg-tls/pg-server.p12 missing — ping-gateway will crash-loop on its admin.json keystore; run scripts/ensure-pinggateway-tls-cert.sh and re-run this script"
fi
# Server-side apply: the CA bundle pushes the secret past the 256KB
# last-applied-configuration annotation limit of client-side apply.
kubectl create secret generic tls-certs \
  --namespace="$NS" \
  --from-file=tls.crt="$ASSET_ROOT/certs/api.ping.demo+2.pem" \
  --from-file=tls.key="$ASSET_ROOT/certs/api.ping.demo+2-key.pem" \
  --from-file=rootCA.pem="$ASSET_ROOT/certs/rootCA.pem" \
  "${CA_BUNDLE_ARG[@]}" \
  "${PG_TLS_ARG[@]}" \
  --dry-run=client -o yaml | kubectl apply --server-side --force-conflicts -f -
info "tls-certs secret applied."

# ── Helper: create one secret from a service's .env file ─────────────────────
# Usage: secret_from_envfile <secret-name> <path-to-.env>
secret_from_envfile() {
  local secret_name="$1" env_file="$2"
  # Optional 3rd arg: pass "legacy-env-only" for a service that deliberately
  # runs its own independent secret architecture outside the shared vault
  # (e.g. oauth-mcp, see oauth-mcp/src/vault.ts's own header comment — it was
  # migrated OFF secrets.vault on purpose). Skips vault consultation and the
  # drift guard-rail entirely for this one call, restoring pre-2026-08-25
  # .env-only behavior. Do not add this for any other service without the
  # same kind of documented, deliberate reason.
  local mode="${3:-}"
  if [ ! -f "$env_file" ]; then
    warn "  $env_file not found — skipping secret $secret_name"
    return
  fi

  local source_file="$env_file" decrypted_file=""
  if grep -qE '^[A-Za-z_][A-Za-z0-9_]*=encrypted:' "$env_file"; then
    local key_file="$ASSET_ROOT/.env.keys"
    local dotenvx_bin="$ASSET_ROOT/demo_api_server/node_modules/.bin/dotenvx"
    [ -f "$key_file" ] || die "Encrypted $env_file requires $key_file"
    [ -x "$dotenvx_bin" ] || die "Encrypted $env_file requires $dotenvx_bin (run npm install in demo_api_server)"
    local private_key
    private_key="$(source "$key_file" && printf '%s' "$DOTENV_PRIVATE_KEY")"
    [ -n "$private_key" ] || die "DOTENV_PRIVATE_KEY is missing from $key_file"
    decrypted_file="$(mktemp)"
    cp "$env_file" "$decrypted_file"
    DOTENV_PRIVATE_KEY="$private_key" "$dotenvx_bin" decrypt -f "$decrypted_file" >/dev/null \
      || { rm -f "$decrypted_file"; die "Could not decrypt $env_file"; }
    source_file="$decrypted_file"
  fi

  # Collect declared variable names (ignore comments/blank lines)
  local keys=()
  while IFS= read -r k; do
    [ -n "$k" ] && keys+=("$k")
  done < <(grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$source_file" | sed 's/=$//' | sort -u)

  # Source the file so quote-wrapped values are unquoted by the shell, then read
  # each declared key's value back. Sourcing here (right before reading) keeps
  # values correct even when two .env files share a key name.
  set -o allexport
  # shellcheck disable=SC1090
  source "$source_file"
  set +o allexport
  [ -z "$decrypted_file" ] || rm -f "$decrypted_file"

  local args=() dry_run_report=()
  for k in "${keys[@]}"; do
    local env_v="${!k:-}"
    if [ "$mode" != "legacy-env-only" ] && vault_has_key "$k"; then
      local vault_v
      vault_v="$(vault_get "$k")"
      if [ -n "$env_v" ] && [ "$env_v" != "$vault_v" ]; then
        die "SECURITY: $k is vault-managed and $env_file has a DIFFERENT non-empty value for it. The vault is authoritative — update $k in $env_file to match the vault value (or leave it blank), never leave a stale copy. (This is exactly the drift class that broke SE introspection on 2026-08-25 — see docs/superpowers/specs/2026-08-25-vault-in-k8s-design.md.)"
      fi
      [ -n "$vault_v" ] && args+=(--from-literal="${k}=${vault_v}")
      dry_run_report+=("$k -> vault")
    else
      [ -n "$env_v" ] && args+=(--from-literal="${k}=${env_v}")
      local mode_suffix=""
      [ "$mode" = "legacy-env-only" ] && mode_suffix=" (legacy-env-only)"
      dry_run_report+=("$k -> .env${mode_suffix}")
    fi
  done
  if [ "${DRY_RUN:-0}" = "1" ]; then
    printf '[dry-run] %s:\n' "$secret_name"
    printf '  %s\n' "${dry_run_report[@]}"
    return
  fi

  if [ "${#args[@]}" -eq 0 ]; then
    warn "  $env_file has no usable keys — skipping $secret_name"
    return
  fi

  kubectl create secret generic "$secret_name" \
    --namespace="$NS" \
    "${args[@]}" \
    --dry-run=client -o yaml | kubectl apply -f -
  info "  $secret_name applied (${#args[@]} keys from $(basename "$(dirname "$env_file")")/.env)"
}

# ── Helix agent key: source from the gitignored <agent>.json keyfile ──────────
# HELIX_API_KEY is a secret, so it is NOT committed (it is absent from the
# configmap and usually from .env). Mirror what the BFF does locally
# (helixAgentKeyLoader.js): read it from <HELIX_AGENT_ID>.json in the repo root
# (ASSET_ROOT) / ~/Documents / ~/Downloads, and patch it into ai-demo-secrets.
# Skipped (leaving the .env value in place) when HELIX_API_KEY is already set in
# the BFF .env, and a no-op when no keyfile is present.
inject_helix_api_key() {
  local bff_env="$ASSET_ROOT/demo_api_server/.env"
  if grep -qE '^HELIX_API_KEY=.+' "$bff_env" 2>/dev/null; then
    info "  HELIX_API_KEY already set in .env — keyfile lookup skipped"
    # Still mirror into langchain-secrets when the BFF .env has the key but
    # langchain_agent/.env does not (typical on SE/AWS deploys).
    local helix_key
    helix_key=$(grep -E '^HELIX_API_KEY=.+' "$bff_env" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"')
    if [ -n "$helix_key" ]; then
      export HELIX_KEY="$helix_key"
      python3 - <<'PY' | kubectl patch secret langchain-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
import json, os
print(json.dumps({"stringData": {"HELIX_API_KEY": os.environ["HELIX_KEY"], "LANGCHAIN_LLM_PROVIDER": "helix"}}))
PY
      info "  HELIX_API_KEY mirrored into langchain-secrets from BFF .env"
    fi
    return
  fi

  # Agent id: .env override wins, else the committed configmap/configStore default.
  local agent="LLM2"
  local env_agent
  env_agent=$(grep -E '^HELIX_AGENT_ID=.+' "$bff_env" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"')
  [ -n "$env_agent" ] && agent="$env_agent"

  local keyfile=""
  local f
  for f in "$ASSET_ROOT/${agent}.json" "$HOME/Documents/${agent}.json" "$HOME/Downloads/${agent}.json"; do
    [ -f "$f" ] && { keyfile="$f"; break; }
  done
  if [ -z "$keyfile" ]; then
    warn "  No HELIX_API_KEY in .env and no ${agent}.json keyfile found — Helix will be unconfigured in-cluster"
    return
  fi

  # Emit the patch JSON from python (keyValue read from the file, never passed on
  # the command line); empty output if the file has no keyValue.
  local patch
  patch=$(python3 - "$keyfile" <<'PY'
import json, sys
try:
    k = (json.load(open(sys.argv[1])).get('keyValue') or '').strip()
except Exception:
    k = ''
if k:
    print(json.dumps({'stringData': {'HELIX_API_KEY': k}}))
PY
)
  if [ -z "$patch" ]; then
    warn "  $(basename "$keyfile") has no keyValue — HELIX_API_KEY not set"
    return
  fi
  printf '%s' "$patch" | kubectl patch secret ai-demo-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
  info "  HELIX_API_KEY injected into ai-demo-secrets from $(basename "$keyfile")"
  # LangChain agent mounts langchain-secrets (not ai-demo-secrets) — mirror the key
  # and default provider so in-cluster /run and WebSocket chat use Helix on SE/AWS.
  printf '%s' "$patch" | python3 -c "
import json, sys
p = json.load(sys.stdin)
p['stringData']['LANGCHAIN_LLM_PROVIDER'] = 'helix'
print(json.dumps(p))
" | kubectl patch secret langchain-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
  info "  HELIX_API_KEY + LANGCHAIN_LLM_PROVIDER=helix mirrored into langchain-secrets"
}

# Mirror GOOGLE_API_KEY from the BFF .env into langchain-secrets so the agent
# can honor an explicit Google/Gemini provider selection in the LLM config UI.
mirror_google_api_key() {
  local bff_env="$ASSET_ROOT/demo_api_server/.env"
  local google_key
  google_key=$(grep -E '^GOOGLE_API_KEY=.+' "$bff_env" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"')
  if [ -z "$google_key" ]; then
    google_key=$(grep -E '^GEMINI_API_KEY=.+' "$bff_env" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"')
  fi
  if [ -z "$google_key" ]; then
    return
  fi
  export GOOGLE_KEY="$google_key"
  python3 - <<'PY' | kubectl patch secret langchain-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
import json, os
print(json.dumps({"stringData": {"GOOGLE_API_KEY": os.environ["GOOGLE_KEY"]}}))
PY
  info "  GOOGLE_API_KEY mirrored into langchain-secrets from BFF .env"
}

