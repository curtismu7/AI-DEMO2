# ── Cloud override: redirect URIs must match the public origin ───────────────
# The BFF .env carries the LOCAL redirect URIs (https://api.ping.demo:4000/...).
# Shipping them verbatim breaks sign-in on any public deployment: these keys are
# bootstrap-authoritative (env beats the runtime config store), so the BFF sends
# PingOne a redirect_uri that only resolves on the dev machine. When
# PUBLIC_APP_URL is set (required for SE/EKS deploys), derive them from it.
#
# If this script is run standalone (e.g. to patch a single secret) without
# PUBLIC_APP_URL exported, fall back to whatever origin is already live in the
# target namespace's configmap instead of silently reverting to local values —
# this happened on live (2026-07-13) and broke sign-in for every user.
override_redirect_uris_for_public_origin() {
  local origin="${CALLER_PUBLIC_APP_URL:-}"
  if [ -z "$origin" ]; then
    origin=$(kubectl get configmap ai-demo-config --namespace="$NS" -o jsonpath='{.data.PUBLIC_APP_URL}' 2>/dev/null || true)
    if [ -n "$origin" ]; then
      warn "  PUBLIC_APP_URL not set — falling back to existing configmap origin $origin"
    fi
  fi
  if [ -z "$origin" ]; then
    warn "  PUBLIC_APP_URL not set and no existing configmap origin found — PINGONE_*_REDIRECT_URI/PUBLIC_APP_URL shipped as-is from .env (local values; sign-in will break on a public deployment)"
    return
  fi
  origin="${origin%/}"
  local patch
  patch=$(printf '{"stringData":{"PUBLIC_APP_URL":"%s","PINGONE_PUBLIC_APP_URL":"%s","PINGONE_ADMIN_REDIRECT_URI":"%s/api/auth/oauth/callback","PINGONE_USER_REDIRECT_URI":"%s/api/auth/oauth/user/callback"}}' "$origin" "$origin" "$origin" "$origin")
  printf '%s' "$patch" | kubectl patch secret ai-demo-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
  info "  PUBLIC_APP_URL/PINGONE_PUBLIC_APP_URL/PINGONE_ADMIN/USER_REDIRECT_URI overridden to match $origin"
}

# ── Privilege gateway URLs: two places, two different fixes ─────────────────
# PRIVILEGE_AGENTLESS_MCPGW_URL (the BFF's Agentless target) and pingone.env's SERVER_URL (the
# gateway's own front door) both shipped from demo_api_server/.env and
# ping-mcpgw/procyon/config/pingone.env as-is — local values that don't
# resolve from inside the cluster.
#
# PRIVILEGE_MCPGW_URL used to be overridden to <origin>/mcpgw/mcp (the app's
# own se-ingress.yaml path). Proven live 2026-08-13 that this categorically
# cannot work for cyonproxy — that port is TLS-native (HTTP/2 via ALPN, its
# own certificate), and nginx re-encrypting it hits TLS handshake failures no
# matter the backend-protocol annotation (HTTP/HTTPS/GRPCS all tried against
# the real gateway). The Agentless Helm release instead exposes Streamable HTTP:
#   https://<namespace-owner>-agentless-mcpgw.ping-devops.com/<app-name>/mcp
# Keep this separate from PRIVILEGE_AGENT_MCPGW_URL: the Priv Agent frontend
# owns its authentication and must not inherit Agentless OAuth configuration.
override_privilege_urls_for_public_origin() {
  local origin="${CALLER_PUBLIC_APP_URL:-}"
  if [ -z "$origin" ]; then
    origin=$(kubectl get configmap ai-demo-config --namespace="$NS" -o jsonpath='{.data.PUBLIC_APP_URL}' 2>/dev/null || true)
  fi
  if [ -z "$origin" ]; then
    warn "  PUBLIC_APP_URL not set and no existing configmap origin found — PRIVILEGE_MCPGW_URL/SERVER_URL shipped as-is (local values; Privilege sign-in and tool calls will fail with fetch/DNS errors in-cluster)"
    return
  fi
  origin="${origin%/}"
  local mcpgw_base="${origin}/mcpgw"
  local app_name="${NS#ping-devops-}"
  local mcpgw_application="${MCPGW_APP_NAME:-$app_name}"
  local mcpgw_client_url="${PRIVILEGE_AGENTLESS_MCPGW_URL:-https://${app_name}-agentless-mcpgw.ping-devops.com/${mcpgw_application}/mcp}"

  # mcpgw binary routes by path prefix: /<app-name>/mcp (not just /mcp).
  # Set MCPGW_APP_NAME env var to the name registered in the Privilege console
  # (AI Security > Agentic Apps). Omit to get the flat /mcp path (won't work
  # with the mcpgw binary unless an app named "" exists, which it won't).
  local mcpgw_app_name="${MCPGW_APP_NAME:-}"
  local mcpgw_mcp_path
  if [ -n "$mcpgw_app_name" ]; then
    mcpgw_mcp_path="${mcpgw_base}/${mcpgw_app_name}/mcp"
  else
    mcpgw_mcp_path="${mcpgw_base}/mcp"
  fi

  local ai_patch
  ai_patch=$(printf '{"stringData":{"PRIVILEGE_AGENTLESS_MCPGW_URL":"%s","PRIVILEGE_MCPGW_URL":"%s"}}' "$mcpgw_client_url" "$mcpgw_client_url")
  printf '%s' "$ai_patch" | kubectl patch secret ai-demo-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
  info "  PRIVILEGE_AGENTLESS_MCPGW_URL/PRIVILEGE_MCPGW_URL overridden to match ${mcpgw_client_url}"

  if [ -f "$ASSET_ROOT/ping-mcpgw/procyon/config/pingone.env" ]; then
    local patched_pingone_env
    patched_pingone_env=$(sed -E "s#^SERVER_URL=.*#SERVER_URL=${mcpgw_base}#" "$ASSET_ROOT/ping-mcpgw/procyon/config/pingone.env")
    local mcpgw_patch
    mcpgw_patch=$(printf '{"stringData":{"pingone.env":%s}}' "$(printf '%s' "$patched_pingone_env" | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))')")
    printf '%s' "$mcpgw_patch" | kubectl patch secret ping-mcpgw-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
    info "  ping-mcpgw-secrets pingone.env SERVER_URL overridden to match $mcpgw_base"
  fi
}

# ── Demo service API key (apikey-dispatch path) ──────────────────────────────
# The gateway pulls DEMO_API_RESOURCE_SERVER_KEY / DEMO_MCP_RESOURCE_SERVER_KEY from the
# BFF vault bridge and presents it to api-resource-server as X-API-Key. In-cluster
# the BFF has no vault password and no LMDB entry, so the bridge falls back to
# the committed default — while api-resource-server refuses to boot with that same
# default. Nothing else provisions the pair in k8s (ensure-service-keys.js is
# local-only), so a fresh deploy either crash-loops the backend or 401s every
# invest/mortgage chip ("backend rejected the service API key"). Single-source
# the key here: prefer the ensure-service-keys value from the repo-root .env,
# else mint one, then ship the SAME value to both sides (ai-demo-secrets for
# the BFF bridge, mortgage-secrets for the backend).
align_service_api_keys() {
  local key
  key=$(grep -E '^API_RESOURCE_SERVER_API_KEY=.+' "$ASSET_ROOT/.env" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"')
  case "$key" in
    ""|demo-mortgage-key-0000|mortgage-compose-dev-key)
      key="mortgage-$(openssl rand -hex 12)"
      warn "  API_RESOURCE_SERVER_API_KEY missing/default in repo-root .env — minted a deploy-local service key"
      ;;
  esac
  printf '{"stringData":{"DEMO_API_RESOURCE_SERVER_KEY":"%s","DEMO_MCP_RESOURCE_SERVER_KEY":"%s"}}' "$key" "$key" \
    | kubectl patch secret ai-demo-secrets --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null
  kubectl create secret generic mortgage-secrets \
    --namespace="$NS" \
    --from-literal="API_RESOURCE_SERVER_API_KEY=${key}" \
    --dry-run=client -o yaml | kubectl apply -f - >/dev/null
  info "  Service API key aligned across ai-demo-secrets (bridge) + mortgage-secrets (backend)"
}

# BFF_INTERNAL_SECRET guards the internal-only endpoints (/internal/vault/service-key,
# /internal/id-token). 03-secrets.yaml.template ships it empty and nothing minted
# one, so both the BFF and the gateway fell back to the committed literal
# 'dev-shared-secret-change-me' — public knowledge in this repo. Any workload with
# pod-network reach to api-server:3001 could then read the backend service keys.
# Mint once and ship the SAME value to every consumer that compares it.
align_internal_secret() {
  local secret
  secret=$(grep -E '^BFF_INTERNAL_SECRET=.+' "$ASSET_ROOT/demo_api_server/.env" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '"')
  case "$secret" in
    ""|dev-shared-secret-change-me)
      secret="$(openssl rand -hex 32)"
      warn "  BFF_INTERNAL_SECRET missing/default in demo_api_server/.env — minted a deploy-local internal secret"
      ;;
  esac
  # mcp-resource-server has no per-service .env / secret of its own (unlike the
  # other four) — create-or-update it here so the patch loop below has a target.
  # Scoped to just this one key, unlike reusing gateway-secrets/ai-demo-secrets,
  # which would leak unrelated worker/agent credentials into the resource server.
  kubectl create secret generic mcp-resource-server-secrets --namespace="$NS" \
    --from-literal=BFF_INTERNAL_SECRET="$secret" --dry-run=client -o yaml \
    | kubectl apply -f - >/dev/null 2>&1 || true
  local s
  # langchain-secrets belongs here too: langchain_agent compares this value in
  # its _gate_internal middleware (src/main.py), but it was omitted, so the
  # agent kept whatever langchain_agent/.env happened to carry. When the two
  # .env files disagreed the mismatch surfaced only as an opaque
  # `{"detail":"Invalid gateway secret"}` 403 on /api/codegraph/query — the
  # Code Explorer smoke check — with nothing naming the secret as the cause.
  # "agent-secrets" in this list is demo_agent_service, a different service.
  for s in ai-demo-secrets gateway-secrets agent-secrets langchain-secrets ping-gateway-secrets mcp-resource-server-secrets; do
    printf '{"stringData":{"BFF_INTERNAL_SECRET":"%s"}}' "$secret" \
      | kubectl patch secret "$s" --namespace="$NS" --type merge --patch-file /dev/stdin >/dev/null 2>&1 || true
  done
  info "  BFF_INTERNAL_SECRET aligned across BFF + gateway + agent + langchain + ping-gateway + mcp-resource-server"
}

