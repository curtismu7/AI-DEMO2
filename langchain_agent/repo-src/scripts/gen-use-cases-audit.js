#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const OUT_PATH = path.join(ROOT, 'docs/use-cases/audit-table.md');

// Require from main checkout if node_modules absent in worktree
const USE_CASES_PATH = path.join(ROOT, 'demo_api_server/config/useCases');
const { USE_CASES } = require(USE_CASES_PATH);

const MATURITY_GLYPH = {
  works: '✅',
  'needs-console-import': '📥',
  'needs-build': '🏗️',
};
function maturityGlyph(m) {
  if (m.startsWith('flag:')) return '🚩';
  return MATURITY_GLYPH[m] || m;
}
function maturityLabel(m) {
  if (m.startsWith('flag:')) return `flag-gated (${m.slice(5)})`;
  return m;
}

const TIER_ORDER = [
  (m) => m === 'works',
  (m) => m.startsWith('flag:'),
  (m) => m === 'needs-console-import',
  (m) => m === 'needs-build',
];
const TIER_HEADINGS = [
  'Works today (`works`)',
  'Flag-gated (`flag:*`)',
  'Needs PingOne console import (`needs-console-import`)',
  'Needs build (`needs-build`)',
];

function buildTable() {
  const lines = [
    '<!-- AUTO-GENERATED by scripts/gen-use-cases-audit.js — do not hand-edit -->',
    '',
    '# Use-Case Audit Table',
    '',
    '> Last generated from `demo_api_server/config/useCases.js`.',
    '> Regenerate: `npm run use-cases:audit:gen` (from `demo_api_server/`).',
    '',
  ];

  for (let t = 0; t < TIER_ORDER.length; t++) {
    const bucket = USE_CASES.filter((uc) => TIER_ORDER[t](uc.maturity));
    if (bucket.length === 0) continue;

    lines.push(`## ${maturityGlyph(bucket[0].maturity)} ${TIER_HEADINGS[t]}`, '');
    lines.push('| ID | Title | Track | Maturity | OWASP | What to Enable |');
    lines.push('|---|---|---|---|---|---|');

    for (const uc of bucket) {
      const owasp = uc.owasp && uc.owasp.threats && uc.owasp.threats.length
        ? `🛡️ ${uc.owasp.threats.join(', ')}`
        : '';
      const whatToEnable = uc.whatToEnable || (uc.maturity === 'needs-build' ? 'See plan' : '');
      lines.push(
        `| ${uc.id} | [${uc.title}](./${uc.useCaseId}.md) | ${uc.track} | ${maturityGlyph(uc.maturity)} ${maturityLabel(uc.maturity)} | ${owasp} | ${whatToEnable} |`
      );
    }
    lines.push('');
  }

  // Summary counts — unknown maturity values surface in an explicit bucket so
  // the table total can never silently drift from the sum of the buckets.
  const KNOWN_MATURITY = (m) =>
    m === 'works' || m.startsWith('flag:') || m === 'needs-console-import' || m === 'needs-build';

  const counts = {
    works: USE_CASES.filter((u) => u.maturity === 'works').length,
    flag: USE_CASES.filter((u) => u.maturity.startsWith('flag:')).length,
    consoleImport: USE_CASES.filter((u) => u.maturity === 'needs-console-import').length,
    build: USE_CASES.filter((u) => u.maturity === 'needs-build').length,
    unknown: USE_CASES.filter((u) => !KNOWN_MATURITY(u.maturity)).length,
  };

  const knownTotal = counts.works + counts.flag + counts.consoleImport + counts.build + counts.unknown;
  if (knownTotal !== USE_CASES.length) {
    // Should never happen; guard against future accounting bugs.
    throw new Error(
      `[gen-use-cases-audit] bucket total ${knownTotal} !== USE_CASES.length ${USE_CASES.length} — fix TIER_ORDER`,
    );
  }

  // Emit "unknown" bucket header + rows if any exist so unrecognised maturity is visible.
  if (counts.unknown > 0) {
    const unknownUcs = USE_CASES.filter((u) => !KNOWN_MATURITY(u.maturity));
    lines.push('## ❓ Unknown maturity', '');
    lines.push('| ID | Title | Track | Maturity | OWASP | What to Enable |');
    lines.push('|---|---|---|---|---|---|');
    for (const uc of unknownUcs) {
      const owasp = uc.owasp?.threats?.length
        ? `🛡️ ${uc.owasp.threats.join(', ')}`
        : '';
      lines.push(
        `| ${uc.id} | [${uc.title}](./${uc.useCaseId}.md) | ${uc.track} | ❓ ${uc.maturity} | ${owasp} | |`
      );
    }
    lines.push('');
  }

  const summaryRows = [
    '## Summary',
    '',
    '| Status | Count |',
    '|---|---|',
    `| ✅ Works | ${counts.works} |`,
    `| 🚩 Flag-gated | ${counts.flag} |`,
    `| 📥 Needs console import | ${counts.consoleImport} |`,
    `| 🏗️ Needs build | ${counts.build} |`,
  ];
  if (counts.unknown > 0) summaryRows.push(`| ❓ Unknown | ${counts.unknown} |`);
  summaryRows.push(`| **Total** | **${USE_CASES.length}** |`, '');
  lines.push(...summaryRows);

  return lines.join('\n');
}

const [, , mode] = process.argv;

if (mode === 'generate') {
  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, buildTable(), 'utf8');
  console.log(`[gen-use-cases-audit] written: ${OUT_PATH}`);
} else if (mode === 'check') {
  const fresh = buildTable();
  let existing = '';
  try { existing = fs.readFileSync(OUT_PATH, 'utf8'); } catch (_) { /* file absent */ }
  if (fresh !== existing) {
    console.error('[gen-use-cases-audit] DRIFT DETECTED: docs/use-cases/audit-table.md is out of date.');
    console.error('Run: npm run use-cases:audit:gen (from demo_api_server/)');
    process.exit(1);
  }
  console.log('[gen-use-cases-audit] OK — audit table is current.');
} else {
  console.error('Usage: gen-use-cases-audit.js generate|check');
  process.exit(1);
}
